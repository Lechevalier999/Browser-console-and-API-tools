function guess() {
  const min = 8;
  const max = 20;
  // Pick a random length from 8 to 20
  const length = Math.floor(Math.random() * (max - min + 1)) + min;
  
  let code = "";
  for (let i = 0; i < length; i++) {
    const randomIndex = Math.floor(Math.random() * characters.length);
    code += characters[randomIndex];
  }
  
  console.log(code);
}
